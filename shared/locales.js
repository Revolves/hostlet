export function normalizeLanguage(value) {
  return String(value || "").toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

export function translate(message, language = "en", values = {}) {
  const source = String(message ?? "");
  let result = source;
  if (language === "zh-CN") {
    result = chinese[source] ?? source;
    const patterns = [
      [/^Entry file (.+) does not exist in this release\.$/, "当前版本中不存在入口文件 $1。"],
      [/^Could not find (.+)\. ZIPs must contain it at the root or inside one top-level folder\.$/, "未找到 $1，请将入口文件放在 ZIP 根目录或唯一顶层文件夹内。"],
      [/^The ZIP did not produce the entry file (.+)\.$/, "ZIP 解压后未找到入口文件 $1。"],
      [/^ZIP archives may contain at most (\d+) files\.$/, "ZIP 最多允许包含 $1 个文件。"],
    ];
    for (const [pattern, replacement] of patterns) {
      if (pattern.test(source)) { result = source.replace(pattern, replacement); break; }
    }
  }
  return result.replace(/\{(\w+)\}/g, (match, key) => Object.hasOwn(values, key) ? String(values[key]) : match);
}
