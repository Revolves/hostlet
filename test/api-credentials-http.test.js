import test from 'node:test';
import assert from 'node:assert/strict';
import http from 'node:http';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import {openDatabase} from '../server/database.js';
import {loadConfig} from '../server/config.js';
import {createApps} from '../server/app.js';

test('verified account manages its own API credentials with password confirmation', async t => {
  const dir=await fs.mkdtemp(path.join(os.tmpdir(),'hostlet-credentials-'));
  const db=openDatabase(':memory:'), mail=[];
  const config=loadConfig({ADMIN_PASSWORD:'test-admin-password', APP_SECRET:'0123456789abcdef0123456789abcdef', DATA_DIR:dir});
  config.registrationEnabled=true;
  const {admin}=await createApps({config,db,accountSender:async m=>mail.push(m)});
  const server=http.createServer(admin);
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  const base=`http://127.0.0.1:${server.address().port}`;
  config.allowedOrigins.splice(0,config.allowedOrigins.length,base);
  t.after(async()=>{await new Promise(resolve=>server.close(resolve));db.close();await fs.rm(dir,{recursive:true,force:true});});
  const call=(url,method='GET',body,cookie,origin=base)=>fetch(base+url,{method,headers:{Origin:origin,...(body?{'Content-Type':'application/json'}:{}),...(cookie?{Cookie:cookie}:{})},...(body?{body:JSON.stringify(body)}:{})});
  const password='a sufficiently long password';
  await call('/api/account/register','POST',{email:'test@example.org',password});
  await call('/api/account/verify','POST',{token:mail[0].token});
  const login=await call('/api/account/login','POST',{email:'test@example.org',password});
  const cookie=login.headers.getSetCookie()[0].split(';')[0];
  const body={name:'CLI',scopes:['read','publish'],expiresAt:Date.now()+86400000,password};
  assert.equal((await call('/api/account/credentials','POST',body)).status,401);
  assert.equal((await call('/api/account/credentials','POST',{...body,password:'wrong'},cookie)).status,401);
  assert.equal((await call('/api/account/credentials','POST',body,cookie,'https://evil.example')).status,403);
  const created=await call('/api/account/credentials','POST',body,cookie);
  assert.equal(created.status,201);
  const credential=await created.json();
  assert.match(credential.token,/^[A-Za-z0-9_-]{43}$/);
  const listed=await (await call('/api/account/credentials','GET',undefined,cookie)).json();
  assert.equal(listed.credentials.length,1);
  assert.equal(JSON.stringify(listed).includes(credential.token),false);
  const bearer={Authorization:`Bearer ${credential.token}`};
  const workspaceCli=await promisify(execFile)(process.execPath,['cli/hostlet.js','workspaces','--json'],{cwd:process.cwd(),env:{...process.env,HOSTLET_URL:base,HOSTLET_TOKEN:credential.token}});
  assert.equal(JSON.parse(workspaceCli.stdout).length,1);
  const spaces=await fetch(base+'/api/cli/workspaces',{headers:bearer});
  assert.equal(spaces.status,200);
  const workspace=(await spaces.json())[0];
  const form=new FormData();form.set('title','CLI demo');form.set('file',new Blob(['<h1>CLI</h1>']),'index.html');
  const published=await fetch(`${base}/api/cli/workspaces/${workspace.id}/pages`,{method:'POST',headers:bearer,body:form});
  assert.equal(published.status,201);
  const page=(await published.json()).page;
  assert.equal(page.accessMode,'private');
  assert.equal(db.prepare("SELECT count(*) n FROM workspace_audit WHERE page_id=? AND action='page.cli_published'").get(page.id).n,1);
  assert.equal((await fetch(`${base}/api/cli/workspaces/${workspace.id}/pages`,{headers:bearer})).status,200);
  assert.equal((await fetch(`${base}/api/cli/workspaces/${workspace.id}/pages/${page.id}`,{method:'DELETE',headers:bearer})).status,404);
  const site=path.join(dir,'site');await fs.mkdir(site);await fs.writeFile(path.join(site,'index.html'),'<h1>Directory</h1>');
  const cli=await promisify(execFile)(process.execPath,['cli/hostlet.js','publish',site,'--workspace',workspace.id,'--title','Directory demo','--json'],{cwd:process.cwd(),env:{...process.env,HOSTLET_URL:base,HOSTLET_TOKEN:credential.token}});
  const result=JSON.parse(cli.stdout);
  assert.equal(result.page.accessMode,'private');
  assert.equal(result.page.title,'Directory demo');
  const listing=await promisify(execFile)(process.execPath,['cli/hostlet.js','pages','--workspace',workspace.id,'--json'],{cwd:process.cwd(),env:{...process.env,HOSTLET_URL:base,HOSTLET_TOKEN:credential.token}});
  assert.ok(JSON.parse(listing.stdout).pages.some(item=>item.id===result.page.id));
  const replacement=await promisify(execFile)(process.execPath,['cli/hostlet.js','publish',site,'--workspace',workspace.id,'--page',result.page.id,'--revision',String(result.page.revision),'--json'],{cwd:process.cwd(),env:{...process.env,HOSTLET_URL:base,HOSTLET_TOKEN:credential.token}});
  assert.equal(JSON.parse(replacement.stdout).page.revision,result.page.revision+1);
  const versions=await promisify(execFile)(process.execPath,['cli/hostlet.js','versions','--workspace',workspace.id,'--page',result.page.id,'--json'],{cwd:process.cwd(),env:{...process.env,HOSTLET_URL:base,HOSTLET_TOKEN:credential.token}});
  assert.equal(JSON.parse(versions.stdout).releases.length,2);
  const readOnly=await (await call('/api/account/credentials','POST',{...body,name:'Read only',scopes:['read']},cookie)).json();
  const deniedForm=new FormData();deniedForm.set('title','Denied');deniedForm.set('file',new Blob(['test']),'index.html');
  assert.equal((await fetch(`${base}/api/cli/workspaces/${workspace.id}/pages`,{method:'POST',headers:{Authorization:`Bearer ${readOnly.token}`},body:deniedForm})).status,401);
  assert.equal((await call(`/api/account/credentials/${credential.id}`,'DELETE',{},cookie)).status,204);
  assert.equal(db.prepare('SELECT revoked_at IS NOT NULL AS revoked FROM api_credentials WHERE id=?').get(credential.id).revoked,1);
  assert.equal((await fetch(base+'/api/cli/workspaces',{headers:bearer})).status,401);
});
